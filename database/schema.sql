-- Storage RLS Politikaları
CREATE POLICY "Görselleri herkes görüntüleyebilir"
  ON storage.objects FOR SELECT
  USING (bucket_id IN ('product-images', 'invoices'));

CREATE POLICY "Giriş yapmış kullanıcı görsel yükleyebilir"
  ON storage.objects FOR INSERT
  WITH CHECK (
    auth.role() = 'authenticated' AND
    bucket_id IN ('product-images', 'invoices')
  );

CREATE POLICY "Giriş yapmış kullanıcı kendi görselini güncelleyebilir/silebilir"
  ON storage.objects FOR DELETE
  USING (
    auth.role() = 'authenticated' AND
    bucket_id IN ('product-images', 'invoices')
  );
